#!/usr/bin/env bash
# Install the jvuey phone remote for the current user.
#
# Sets up the web-remote service. Does not need root, and does not touch the
# selector itself - jvuey23.py runs the same way it always did.
#
#   ./install.sh            install and start
#   ./install.sh --uninstall remove the service (leaves files alone)

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT="$UNIT_DIR/jvuey-remote.service"
PORT="${JVUEY_REMOTE_PORT:-8080}"

say()  { printf '\033[1m%s\033[0m\n' "$*"; }
warn() { printf '  ! %s\n' "$*" >&2; }
ok()   { printf '  + %s\n' "$*"; }

if [ "${1:-}" = "--uninstall" ]; then
    systemctl --user disable --now jvuey-remote 2>/dev/null || true
    rm -f "$UNIT"
    systemctl --user daemon-reload
    say "Removed. Files in $HERE are untouched."
    echo "  Also remove the autostart line from ~/.zshrc if you added one,"
    echo "  and close the firewall port if you opened it."
    exit 0
fi

say "Checking what's needed"
missing=0
for cmd in uv mpv python3; do
    if path="$(command -v "$cmd" 2>/dev/null)"; then
        ok "$cmd -> $path"
    else
        warn "$cmd NOT FOUND"
        missing=1
    fi
done
command -v tmux >/dev/null && ok "tmux -> $(command -v tmux)" \
    || warn "tmux not found (only needed for the console autostart)"
[ "$missing" -eq 0 ] || { warn "Install the missing tools first."; exit 1; }

for f in jvuey23.py jvuey-remote.py jvuey-loop.sh; do
    [ -f "$HERE/$f" ] || { warn "missing $HERE/$f"; exit 1; }
    chmod +x "$HERE/$f"
done
ok "scripts are executable"

# systemd user services get a minimal PATH, so pin the directories the tools
# actually live in on THIS machine rather than guessing.
UV_DIR="$(dirname "$(command -v uv)")"
MPV_DIR="$(dirname "$(command -v mpv)")"
SERVICE_PATH="$UV_DIR:$MPV_DIR:$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin"

say "Writing $UNIT"
mkdir -p "$UNIT_DIR"
cat > "$UNIT" <<UNITEOF
[Unit]
Description=jvuey phone remote (web UI)
After=network.target

[Service]
Type=simple
# Generated by install.sh for this machine - re-run it if your paths change.
Environment=PATH=$SERVICE_PATH
Environment=JVUEY_REMOTE_PORT=$PORT
ExecStart=$HERE/jvuey-remote.py
Restart=always
RestartSec=3

[Install]
WantedBy=default.target
UNITEOF
ok "ExecStart=$HERE/jvuey-remote.py"
ok "port $PORT"

systemctl --user daemon-reload
systemctl --user enable --now jvuey-remote
sleep 2

if systemctl --user is-active --quiet jvuey-remote; then
    ok "service is running"
else
    warn "service failed to start:"
    journalctl --user -u jvuey-remote -n 15 --no-pager -o cat >&2
    exit 1
fi

if command -v loginctl >/dev/null && [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" != "yes" ]; then
    loginctl enable-linger "$USER" 2>/dev/null \
        && ok "lingering enabled (service survives logout)" \
        || warn "could not enable lingering - see the README for the declarative way"
fi

IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
[ -n "$IP" ] || IP="<this-machine>"

cat <<DONE

$(say "Done. The remote is at:")

    http://$IP:$PORT/remote

Two things install.sh deliberately does not do for you:

  1. Open the firewall. Nothing can reach port $PORT until you do.
       NixOS      networking.firewall.allowedTCPPorts = [ $PORT ];  then rebuild
       ufw        sudo ufw allow $PORT/tcp
       firewalld  sudo firewall-cmd --add-port=$PORT/tcp --permanent && sudo firewall-cmd --reload

  2. Start the selector on your TV console. Add this to ~/.zshrc, ABOVE any
     block that launches tmux:

       source $HERE/autostart.zsh

     Or just run $HERE/jvuey-loop.sh by hand.
DONE
